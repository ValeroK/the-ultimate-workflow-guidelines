'use strict';

// Card links of PLAN-memory-index: the link check for AGENTS.md, CLAUDE.md, memory.md and
// memory/**/*.md. brokenLinks is pure (texts and an exists callback, no file system); the commands
// `links` and `memory check` run here through the real CLI.

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const PAYLOAD = path.join(__dirname, '..', '..', '.cursor-plugin', 'ultimate-workflow');
const EXPERTS = path.join(PAYLOAD, 'experts', 'experts.js');
const links = require(path.join(PAYLOAD, 'lib', 'links.js'));
const memory = require(path.join(PAYLOAD, 'lib', 'memory.js'));

const existing = (...names) => (p) => names.includes(p);

function cli(root, ...args) {
  const r = spawnSync(process.execPath, [EXPERTS, ...args, '--root', root], { encoding: 'utf8' });
  return { status: r.status, out: `${r.stdout}${r.stderr}` };
}

function project(files) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'uw-links-'));
  for (const [name, text] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(root, name)), { recursive: true });
    fs.writeFileSync(path.join(root, name), text);
  }
  return root;
}

// ---- brokenLinks (pure) ------------------------------------------------------------------------

test('a link to a missing file is reported with file, line and target; one to an existing file passes', () => {
  const files = { 'memory.md': '# Memory\n\n[ok](a.md) and [gone](missing.md)\n' };
  assert.deepStrictEqual(links.brokenLinks(files, existing('a.md')), [{ file: 'memory.md', line: 3, target: 'missing.md' }]);
  assert.deepStrictEqual(links.brokenLinks(files, existing('a.md', 'missing.md')), []);
});

test('a fragment or a query is stripped before the file is looked up', () => {
  const files = { 'memory.md': '[x](./a.md#part)\n[y](a.md?x=1)\n' };
  assert.deepStrictEqual(links.brokenLinks(files, existing('a.md')), []);
});

test('a percent-encoded path and an angle-bracketed path resolve', () => {
  const files = { 'memory.md': '[x](my%20file.md)\n[y](<my file.md>)\n' };
  assert.deepStrictEqual(links.brokenLinks(files, existing('my file.md')), []);
});

test('web links, anchors, placeholders and fenced code are not checked', () => {
  const files = {
    'memory.md': [
      '[a](https://example.com/x.md)',
      '[b](#section)',
      '[c]({placeholder}/x.md)',
      '[d](mailto:me@example.com)',
      '```',
      '[e](in-backtick-fence.md)',
      '```',
      '~~~',
      '[f](in-tilde-fence.md)',
      '~~~',
      '',
    ].join('\n'),
  };
  assert.deepStrictEqual(links.brokenLinks(files, existing()), []);
});

test('a link after a closed fence is checked again', () => {
  const files = { 'memory.md': '```\n[e](in-fence.md)\n```\n[g](after.md)\n' };
  assert.deepStrictEqual(links.brokenLinks(files, existing()), [{ file: 'memory.md', line: 4, target: 'after.md' }]);
});

test('an @path import line is checked: a missing target fails, an existing one passes', () => {
  assert.deepStrictEqual(links.brokenLinks({ 'CLAUDE.md': '@AGENTS.md\n' }, existing('AGENTS.md')), []);
  assert.deepStrictEqual(links.brokenLinks({ 'CLAUDE.md': '@AGENTS.md\n' }, existing()), [{ file: 'CLAUDE.md', line: 1, target: 'AGENTS.md' }]);
});

test('a link in a file under memory/ resolves from that folder, not from the root', () => {
  const files = { 'memory/a.md': '[b](b.md)\n[up](../memory.md)\n' };
  assert.deepStrictEqual(links.brokenLinks(files, existing('memory/b.md', 'memory.md')), []);
  assert.deepStrictEqual(links.brokenLinks(files, existing('b.md', 'memory.md')), [{ file: 'memory/a.md', line: 1, target: 'b.md' }]);
});

test('a home-relative import (@~/...) is not a path in the project', () => {
  assert.deepStrictEqual(links.brokenLinks({ 'CLAUDE.md': '@~/.claude/my-rules.md\n' }, existing()), []);
});

test('a link shown as an example inside an inline code span is not checked; one beside it is', () => {
  const files = { 'memory.md': 'Write `[text](example-missing.md)` like so, see [real](gone.md).\n' };
  assert.deepStrictEqual(links.brokenLinks(files, existing()), [{ file: 'memory.md', line: 1, target: 'gone.md' }]);
});

// ---- the commands ------------------------------------------------------------------------------

const HEADER = ['---', 'description: About A.', 'read_when:', '  paths: [src/**]', '---', '', '# A', ''].join('\n');
const START = '<!-- uw:memory-index:start generated by: node experts/experts.js memory index; do not edit between the markers -->';
const END = '<!-- uw:memory-index:end -->';
const INDEXED = ['# Memory', '', START, '- [memory/a.md](memory/a.md) - About A. **Read when** `src/**`.', END, ''].join('\n');

function migrated(extra = {}) {
  return project({ 'memory.md': INDEXED, 'memory/a.md': HEADER, 'src/x.js': 'x\n', ...extra });
}

test('links exits 1 and names file, line and target for a broken link', () => {
  const root = migrated({ 'AGENTS.md': 'one\n[gone](nope.md)\n' });
  const r = cli(root, 'links');
  assert.strictEqual(r.status, 1, r.out);
  assert.match(r.out, /AGENTS\.md:2/);
  assert.match(r.out, /nope\.md/);
});

test('links exits 0 when every link resolves, including the @AGENTS.md import', () => {
  const root = migrated({ 'AGENTS.md': '[ok](memory.md)\n', 'CLAUDE.md': '@AGENTS.md\n' });
  const r = cli(root, 'links');
  assert.strictEqual(r.status, 0, r.out);
});

test('links fails on a CLAUDE.md import whose target is missing', () => {
  const root = migrated({ 'CLAUDE.md': '@MISSING.md\n' });
  const r = cli(root, 'links');
  assert.strictEqual(r.status, 1, r.out);
  assert.match(r.out, /CLAUDE\.md:1/);
});

test('a file outside the scope (a docs page) is not checked', () => {
  const root = migrated({ 'docs/page.md': '[gone](nope.md)\n' });
  assert.strictEqual(cli(root, 'links').status, 0);
  assert.strictEqual(cli(root, 'memory', 'check').status, 0);
});

test('memory check fails on a broken link even when the index is current', () => {
  const root = migrated({ 'memory/b.md': '---\ndescription: B.\nread_when:\n  keywords: [bee]\n---\n[gone](nope.md)\n' });
  // regenerate so the index is current for both topicals
  assert.strictEqual(cli(root, 'memory', 'index').status, 0);
  const r = cli(root, 'memory', 'check');
  assert.strictEqual(r.status, 1, r.out);
  assert.match(r.out, /memory\/b\.md:6/);
  assert.match(r.out, /nope\.md/);
});

test('memory check passes when the index and the links are both fine', () => {
  const root = migrated({ 'AGENTS.md': '[m](memory.md)\n' });
  const r = cli(root, 'memory', 'check');
  assert.strictEqual(r.status, 0, r.out);
});

test('a header path glob that matches no file is a warning and the exit code stays 0', () => {
  const root = migrated({ 'memory/a.md': HEADER.replace('src/**', 'nowhere/**') });
  assert.strictEqual(cli(root, 'memory', 'index').status, 0);
  const r = cli(root, 'memory', 'check');
  assert.strictEqual(r.status, 0, r.out);
  assert.match(r.out, /warning:.*memory\/a\.md.*nowhere\/\*\*/);
});

test('a header path glob that matches a file gives no warning', () => {
  const r = cli(migrated(), 'memory', 'check');
  assert.strictEqual(r.status, 0, r.out);
  assert.doesNotMatch(r.out, /matches no file/);
});

// The glob semantics are the ones experts.js already has (globToRegExp): `*` stays in one folder,
// a leading `**/` also matches the root.
function warnsFor(glob, files) {
  const root = migrated({ 'memory/a.md': HEADER.replace('src/**', glob), ...files });
  assert.strictEqual(cli(root, 'memory', 'index').status, 0);
  const r = cli(root, 'memory', 'check');
  assert.strictEqual(r.status, 0, r.out);
  return /matches no file/.test(r.out);
}

test('header path globs: * stays inside one folder', () => {
  assert.strictEqual(warnsFor('lib/*.js', { 'lib/a.js': 'x\n' }), false);
  assert.strictEqual(warnsFor('lib/*.js', { 'lib/deep/a.js': 'x\n' }), true);
});

test('header path globs: a leading **/ matches the root and any depth', () => {
  assert.strictEqual(warnsFor('**/q.js', { 'q.js': 'x\n' }), false, 'at the root');
  assert.strictEqual(warnsFor('**/q.js', { 'a/b/q.js': 'x\n' }), false, 'deep');
  assert.strictEqual(warnsFor('**/q.js', { 'a/y.js': 'x\n' }), true, 'no such name');
});

test('header path globs: a trailing ** matches files at any depth below the folder', () => {
  assert.strictEqual(warnsFor('lib/**', { 'lib/deep/er/a.js': 'x\n' }), false, 'deep only');
  assert.strictEqual(warnsFor('lib/**', { 'lib/a.js': 'x\n' }), false, 'one level');
  assert.strictEqual(warnsFor('lib/**', { 'other/a.js': 'x\n' }), true, 'other folder');
});

test('header path globs: a path ending in / covers the files below the folder', () => {
  assert.strictEqual(warnsFor('lib/', { 'lib/deep/a.js': 'x\n' }), false, 'a file lies below');
  assert.strictEqual(warnsFor('lib/', { 'other/a.js': 'x\n' }), true, 'no file lies below');
});

test('cueWarnings and the matcher agree: a header path the matcher covers for a file is never warned about', () => {
  const shapes = ['only/', 'none/', 'sub/**', 'edge/**', 'flat/*.js', '**/name.js', 'nothing/**'];
  const topicals = (i) => `memory/t${i}.md`;
  const extra = { 'only/deep/a.js': 'x\n', 'sub/x/y.js': 'x\n', edge: 'x\n', 'flat/deep/z.js': 'x\n', 'name.js': 'x\n' };
  shapes.forEach((glob, i) => { extra[topicals(i)] = HEADER.replace('src/**', glob); });
  const root = migrated(extra);
  assert.strictEqual(cli(root, 'memory', 'index').status, 0);
  const r = cli(root, 'memory', 'check');
  assert.strictEqual(r.status, 0, r.out);
  const files = links.listFiles(root);
  shapes.forEach((glob, i) => {
    const topical = { [topicals(i)]: HEADER.replace('src/**', glob) };
    const matched = files.some((f) => memory.matchTopicals('', topical, { title: 'a card', paths: [f], carried: [] }).length > 0);
    assert.strictEqual(r.out.includes(`${topicals(i)}: path "${glob}" matches no file`), !matched, `${glob}: the matcher ${matched ? 'covers' : 'covers no'} file`);
  });
  assert.ok(shapes.some((_, i) => r.out.includes(`${topicals(i)}: path`)), 'some shape is warned about');
  assert.ok(shapes.some((_, i) => !r.out.includes(`${topicals(i)}: path`)), 'some shape is not');
});

test('the links command reads only the entry and memory files, not the whole tree', () => {
  const root = migrated({ 'AGENTS.md': '[ok](memory.md)\n', 'src/deep/y.js': 'y\n' });
  const real = fs.readdirSync;
  const read = [];
  fs.readdirSync = (dir, ...rest) => {
    read.push(String(dir));
    return real(dir, ...rest);
  };
  try {
    assert.strictEqual(links.cli(['--root', root], process.cwd(), () => {}, (m) => { throw new Error(m); }), 0);
  } finally {
    fs.readdirSync = real;
  }
  assert.ok(read.length > 0, 'the project was read');
  assert.deepStrictEqual(read.filter((d) => d.includes(`${path.sep}src`)), [], 'src/ was never listed');
});

// ---- carried: the write order of memory index / migrate ----------------------------------------

test('memory migrate writes the topicals before memory.md, so a failed write never leaves an index naming unwritten headers', () => {
  const original = '- [memory/a.md](memory/a.md) - About A. **Read when** editing `src/**`.\n';
  const root = project({ 'memory.md': original, 'memory/a.md': '# A\n\nbody\n' });
  const realWrite = fs.writeFileSync;
  const written = [];
  fs.writeFileSync = (file, ...rest) => {
    written.push(path.basename(String(file)));
    // the second write fails
    if (written.length === 2) throw new Error('disk full');
    return realWrite(file, ...rest);
  };
  try {
    assert.throws(() => memory.cli(['migrate', '--root', root], process.cwd(), () => {}, (m) => { throw new Error(m); }), /disk full/);
  } finally {
    fs.writeFileSync = realWrite;
  }
  assert.deepStrictEqual(written, ['a.md', 'memory.md']);
  assert.strictEqual(fs.readFileSync(path.join(root, 'memory.md'), 'utf8'), original);
});
