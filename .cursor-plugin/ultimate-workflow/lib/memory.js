'use strict';

// Topical memory headers and the generated index in memory.md (PLAN-memory-index, card index).
//
// parseHeader, renderIndex and migrateTexts are pure: text in, text out, no file system. The
// commands `memory index|check|migrate` wrap them with the file system (see cli).

const fs = require('node:fs');
const path = require('node:path');
const links = require('./links.js');
const cardsLib = require('../experts/cards.js');

const START_PREFIX = '<!-- uw:memory-index:start';
const START_LINE = `${START_PREFIX} generated by: node experts/experts.js memory index; do not edit between the markers -->`;
const END_LINE = '<!-- uw:memory-index:end -->';
const INDEX_COMMAND = 'node experts/experts.js memory index';
const READ_WHEN = '**Read when**';
// "- [memory/x.md](memory/x.md) - description **Read when** cues" (the old format used an em dash).
const ENTRY = /^- \[[^\]]+\]\(([^)]+)\)\s+[—–-]\s+(.*)$/;
const LEADING_VERB = /^(?:editing|touching|changing|diagnosing|deciding(?: whether)?)\b\s*/i;

const eolOf = (text) => (text.includes('\r\n') ? '\r\n' : '\n');
const unquote = (s) => s.replace(/^(["'])(.*)\1$/, '$2');

// ---- the header --------------------------------------------------------------------------------

function inlineList(value) {
  const m = /^\[(.*)\]$/.exec(value);
  return m ? m[1].split(',').map((s) => unquote(s.trim())).filter(Boolean) : null;
}

/**
 * Parse the front matter of a topical. Returns { header, errors }: header is null when the file
 * has none or when it is invalid; errors holds { line, reason } (1-based line) for an invalid one.
 */
function parseHeader(text) {
  const lines = text.replace(/^﻿/, '').split(/\r?\n/);
  if (lines[0].trimEnd() !== '---') return { header: null, errors: [] };
  const close = lines.findIndex((l, i) => i > 0 && l.trimEnd() === '---');
  if (close < 0) return { header: null, errors: [{ line: 1, reason: 'unclosed header: no closing --- line' }] };

  const errors = [];
  const err = (line, reason) => errors.push({ line, reason });
  const h = {};
  let inReadWhen = false;
  let list = null;
  for (let i = 1; i < close; i++) {
    const raw = lines[i];
    const n = i + 1;
    if (!raw.trim()) continue;
    if (/^\s*\t/.test(raw)) {
      err(n, 'a tab in the indentation is not allowed');
      continue;
    }
    const indent = raw.length - raw.trimStart().length;
    const s = raw.trim();
    if (s === '-' || s.startsWith('- ')) {
      if (list) list.push(unquote(s.slice(1).trim()));
      else err(n, 'a list item outside a paths or keywords list');
      continue;
    }
    const m = /^([A-Za-z_]+):\s*(.*)$/.exec(s);
    if (!m) {
      err(n, 'not a "key: value" line');
      continue;
    }
    const [, key, value] = m;
    if (indent === 0) {
      list = null;
      inReadWhen = false;
      if (key === 'read_when') {
        inReadWhen = true;
        if (value) err(n, 'read_when takes a nested map, not a value');
      } else if (key === 'description' || key === 'updated') h[key] = unquote(value);
      else err(n, `unknown key "${key}"`);
    } else if (inReadWhen && indent === 2) {
      list = null;
      if (key !== 'paths' && key !== 'keywords') err(n, `unknown key "${key}"`);
      else if (value === '') h[key] = list = [];
      else if (inlineList(value)) h[key] = inlineList(value);
      else err(n, `${key} takes [a, b] or "- item" lines`);
    } else if (inReadWhen) err(n, 'a nested map deeper than read_when is not allowed');
    else err(n, 'unexpected indentation');
  }
  if (!errors.length) {
    if (!h.description) err(1, 'description is required');
    if (!(h.paths && h.paths.length) && !(h.keywords && h.keywords.length)) err(1, 'read_when needs at least one of paths or keywords');
    if (h.updated !== undefined && !/^\d{4}-\d{2}-\d{2}$/.test(h.updated)) err(1, 'updated must be YYYY-MM-DD');
  }
  if (errors.length) return { header: null, errors };
  return { header: { description: h.description, paths: h.paths || [], keywords: h.keywords || [], ...(h.updated ? { updated: h.updated } : {}) }, errors };
}

// ---- the index ---------------------------------------------------------------------------------

// The line range of the marked block, or null. A start without an end is refused, never guessed.
function findBlock(lines) {
  const start = lines.findIndex((l) => l.startsWith(START_PREFIX));
  if (start < 0) return null;
  const end = lines.findIndex((l, i) => i > start && l.trimEnd() === END_LINE);
  if (end < 0) throw new Error(`memory.md has "${START_PREFIX}" but no "${END_LINE}"`);
  return { start, end };
}

function indexLine(file, header) {
  const cues = [...header.paths.map((p) => `\`${p}\``), ...header.keywords];
  return `- [${file}](${file}) - ${header.description} ${READ_WHEN} ${cues.join(', ')}.`;
}

// The generated lines for the topicals that have a valid header, sorted by path.
function indexLines(topicals) {
  return Object.keys(topicals)
    .sort()
    .map((file) => ({ file, header: parseHeader(topicals[file]).header }))
    .filter((t) => t.header)
    .map((t) => indexLine(t.file, t.header));
}

/** The new memory.md text: only what lies between the markers is rewritten (or the block is appended). */
function renderIndex(memoryMd, topicals) {
  const eol = eolOf(memoryMd);
  const lines = memoryMd.split(eol);
  const block = findBlock(lines);
  const generated = indexLines(topicals);
  if (!block) {
    const base = memoryMd.endsWith('\n') ? memoryMd : memoryMd + eol;
    return `${base}${eol}${[START_LINE, ...generated, END_LINE].join(eol)}${eol}`;
  }
  lines.splice(block.start + 1, block.end - block.start - 1, ...generated);
  return lines.join(eol);
}

// ---- the migration -----------------------------------------------------------------------------

// The topical text with a header written from its memory.md entry, or null when the entry has no
// description or no cue to build a valid header from.
function withHeader(text, entryRest) {
  const at = entryRest.indexOf(READ_WHEN);
  if (at < 0) return null;
  const description = entryRest.slice(0, at).trim();
  const cueText = entryRest.slice(at + READ_WHEN.length).trim().replace(/\.$/, '');
  const terms = [...cueText.matchAll(/`([^`]+)`/g)].map((m) => m[1]);
  const phrases = cueText
    .replace(/`[^`]+`/g, '')
    .split(',')
    .map((p) => unquote(p.trim().replace(/^(?:or|and)(?:\s+|$)/, '').replace(LEADING_VERB, '').trim()))
    .filter((p) => /\w/.test(p));
  const paths = [...new Set(terms.filter((t) => /[/*]/.test(t)))];
  const keywords = [...new Set([...terms.filter((t) => !/[/*]/.test(t)), ...phrases])];
  if (!description || !(paths.length || keywords.length)) return null;

  const eol = eolOf(text);
  const body = text.split(eol);
  const at2 = body.findIndex((l) => /^>?\s*Last updated \d{4}-\d{2}-\d{2}\.?\s*$/i.test(l));
  let updated = null;
  if (at2 >= 0) {
    updated = /\d{4}-\d{2}-\d{2}/.exec(body[at2])[0];
    body.splice(at2, 1);
    if (body[at2 - 1] === '' && body[at2] === '') body.splice(at2, 1);
  }
  const head = [
    '---',
    `description: ${description}`,
    'read_when:',
    ...(paths.length ? ['  paths:', ...paths.map((p) => `    - ${p}`)] : []),
    ...(keywords.length ? ['  keywords:', ...keywords.map((k) => `    - ${k}`)] : []),
    ...(updated ? [`updated: ${updated}`] : []),
    '---',
    '',
  ];
  return head.join(eol) + eol + body.join(eol);
}

/**
 * What `memory migrate` writes: { memoryMd, topicals }. Each topical with no header gets one built
 * from its linked entry in memory.md; the linked entries are replaced by the marked block where the
 * first one stood. A topical that cannot get a valid header keeps its entry and its text.
 */
function migrateTexts(memoryMd, topicals) {
  const eol = eolOf(memoryMd);
  const lines = memoryMd.split(eol);
  const block = findBlock(lines);
  const migrated = { ...topicals };
  const dropped = new Set();
  lines.forEach((line, i) => {
    if (block && i >= block.start && i <= block.end) return;
    const entry = ENTRY.exec(line);
    if (!entry || !Object.hasOwn(topicals, entry[1])) return;
    const parsed = parseHeader(topicals[entry[1]]);
    if (parsed.errors.length) return;
    if (!parsed.header) {
      const text = withHeader(topicals[entry[1]], entry[2]);
      if (!text) return;
      migrated[entry[1]] = text;
    }
    dropped.add(i);
  });
  const first = Math.min(...dropped);
  const kept = [];
  lines.forEach((line, i) => {
    if (!dropped.has(i)) kept.push(line);
    else if (i === first && !block) kept.push(START_LINE, END_LINE);
  });
  return { memoryMd: renderIndex(kept.join(eol), migrated), topicals: migrated };
}

// ---- the commands ------------------------------------------------------------------------------

function readProject(root) {
  const memoryFile = path.join(root, 'memory.md');
  if (!fs.existsSync(memoryFile)) throw new Error(`no memory.md in ${root} (use --root)`);
  const dir = path.join(root, 'memory');
  const topicals = {};
  if (fs.existsSync(dir)) {
    for (const f of fs.readdirSync(dir).filter((n) => n.endsWith('.md')).sort()) topicals[`memory/${f}`] = fs.readFileSync(path.join(dir, f), 'utf8');
  }
  return { memoryFile, memoryMd: fs.readFileSync(memoryFile, 'utf8'), topicals };
}

function entryLines(text) {
  const lines = text.split(eolOf(text));
  const block = findBlock(lines);
  return block ? lines.slice(block.start + 1, block.end).filter((l) => l.trim()) : null;
}

const entryTarget = (line) => (/^- \[[^\]]+\]\(([^)]+)\)/.exec(line) || [])[1];

// { errors, warnings } for a project: an invalid header, a stale or hand-edited block fail;
// anything not yet migrated only warns.
function check(memoryMd, topicals) {
  const errors = [];
  const warnings = [];
  for (const [file, text] of Object.entries(topicals)) {
    const parsed = parseHeader(text);
    for (const e of parsed.errors) errors.push(`${file}:${e.line}: invalid header: ${e.reason}`);
    if (!parsed.header && !parsed.errors.length) warnings.push(`${file}: not migrated (no header); run: node experts/experts.js memory migrate`);
  }
  const current = entryLines(memoryMd);
  if (!current) {
    warnings.push('memory.md: not migrated (no index markers); run: node experts/experts.js memory migrate');
    return { errors, warnings };
  }
  if (renderIndex(memoryMd, topicals) === memoryMd) return { errors, warnings };
  const expected = new Map(entryLines(renderIndex(memoryMd, topicals)).map((l) => [entryTarget(l), l]));
  const seen = new Set();
  for (const line of current) {
    const target = entryTarget(line);
    seen.add(target);
    if (!expected.has(target)) errors.push(`memory.md lists ${target || `"${line}"`}, which is not an indexable topical (missing file or invalid header)`);
    else if (expected.get(target) !== line) errors.push(`memory.md: the index line for ${target} differs from its header (hand-edited?)`);
  }
  for (const target of expected.keys()) if (!seen.has(target)) errors.push(`${target} is missing from the index in memory.md`);
  if (!errors.length) errors.push('memory.md: the generated block differs from the headers');
  return { errors, warnings };
}

// Header paths that match none of the project's files.
function cueWarnings(topicals, files) {
  const { globToRegExp } = require('../experts/experts.js'); // lazy: experts.js requires this file
  const warnings = [];
  for (const [file, text] of Object.entries(topicals)) {
    const { header } = parseHeader(text);
    for (const glob of header ? header.paths : []) {
      // globToRegExp reads a trailing `**` as one level; in a header `src/**` means everything below src/.
      const re = globToRegExp(glob.replace(/\*\*$/, '**/*'));
      if (!files.some((f) => re.test(f))) warnings.push(`${file}: path "${glob}" matches no file`);
    }
  }
  return warnings;
}

// ---- matching ----------------------------------------------------------------------------------

const STOP = new Set(['when', 'what', 'with', 'this', 'that', 'from', 'into', 'read', 'file', 'files', 'adding', 'editing', 'touching', 'changing', 'about', 'which', 'there', 'their', 'before', 'after', 'whether']);

// Whether the globs cover the file, by the glob rule the plan's card paths use. experts.js requires
// this module, so it is loaded at the call and not at the top.
const covers = (globs, file) => cardsLib.covers(globs, file, require('../experts/experts.js').globToRegExp);

const cardText = (card) => [card.title, ...card.paths, ...(card.carried || [])].join('\n').toLowerCase();
// The plain words of five letters or more in a cue, as the pre-header matcher took them.
const cueWords = (cue) => cue.toLowerCase().split(/[^a-z0-9-]+/).filter((w) => w.length >= 5 && !STOP.has(w));
const titleWordsOf = (card) => new Set(String(card.title).toLowerCase().split(/[^a-z0-9]+/).filter(Boolean));

// A topical with no header: its memory.md "Read when" cue, matched as before the headers existed. A
// backticked term (globs and trailing slashes stripped) found in the card's text, or a plain word of
// five letters or more that is a word of its title.
function cueMatches(memoryMd, card, text) {
  const titleWords = titleWordsOf(card);
  const out = new Set();
  for (const line of memoryMd.split(/\r?\n/)) {
    const link = /\]\((memory\/[^)\s]+\.md)\)/.exec(line);
    const at = line.search(/read when/i);
    if (!link || at === -1) continue;
    const cue = line.slice(at + 9);
    const terms = [...cue.matchAll(/`([^`]+)`/g)].map((m) => m[1].replace(/\*+/g, '').replace(/\/+$/, '').trim().toLowerCase()).filter((t) => t.length >= 3);
    const words = cueWords(cue.replace(/`[^`]*`/g, ' '));
    if (terms.some((t) => text.includes(t)) || words.some((w) => titleWords.has(w))) out.add(link[1]);
  }
  return out;
}

const keywordRe = (k) => new RegExp(`(?<![a-z0-9])${k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?![a-z0-9])`, 'i');

/**
 * The topicals a card should read: [{ file, how }] with how 'path', 'keyword' or 'cue', path matches
 * first, then keyword, then cue, each by path. A header path matches when it and one of the card's
 * paths (taken relative to memoryRoot; a path outside it never matches) cover one another, by the
 * glob rule the plan's card paths use; a keyword matches as a whole word or phrase in the card's
 * title, paths or carried items, or by a word of five letters or more that is a word of the title (the
 * old cue rule, so migrating loses no match). A topical with no header falls back to its memory.md cue; one with
 * an invalid header matches nothing. Reads nothing from disk.
 */
function matchTopicals(memoryMd, topicals, card, memoryRoot = '') {
  const text = cardText(card);
  const prefix = memoryRoot ? `${memoryRoot.replace(/\/+$/, '')}/` : '';
  const own = card.paths.map(cardsLib.cleanPath).filter((p) => p.startsWith(prefix)).map((p) => p.slice(prefix.length));
  const cue = cueMatches(memoryMd, card, text);
  const titleWords = titleWordsOf(card);
  const found = [];
  for (const file of Object.keys(topicals).sort()) {
    const { header, errors } = parseHeader(topicals[file]);
    if (header) {
      if (header.paths.some((g) => own.some((p) => covers([g], p) || covers([p], g)))) found.push({ file, how: 'path' });
      else if (header.keywords.some((k) => keywordRe(k).test(text) || cueWords(k).some((w) => titleWords.has(w)))) found.push({ file, how: 'keyword' });
    } else if (!errors.length && cue.has(file)) found.push({ file, how: 'cue' });
  }
  return ['path', 'keyword', 'cue'].flatMap((how) => found.filter((m) => m.how === how));
}

/**
 * `memory index|check|migrate [--root <dir>]`. Prints through write and returns the exit code
 * (check returns 1 on a failure); fail is for a command that cannot run at all.
 */
function cli(argv, cwd, write, fail) {
  const [command] = argv;
  const at = argv.indexOf('--root');
  const root = path.resolve(cwd, at >= 0 ? argv[at + 1] || fail('--root needs a folder') : '.');
  if (!['index', 'check', 'migrate'].includes(command)) return fail('usage: memory index|check|migrate [--root <dir>]');
  const project = readProject(root);

  if (command === 'check') {
    const files = links.listFiles(root);
    const { errors, warnings } = check(project.memoryMd, project.topicals);
    const linkErrors = links.projectLinkErrors(root);
    for (const w of [...warnings, ...cueWarnings(project.topicals, files)]) write(`warning: ${w}\n`);
    for (const e of [...errors, ...linkErrors]) write(`error: ${e}\n`);
    if (errors.some((e) => !e.includes('invalid header'))) write(`fix the index with: ${INDEX_COMMAND}\n`);
    const problems = errors.length + linkErrors.length;
    write(problems ? `memory check: ${problems} problem(s)\n` : 'memory check: ok\n');
    return problems ? 1 : 0;
  }

  const next = command === 'index' ? { memoryMd: renderIndex(project.memoryMd, project.topicals), topicals: project.topicals } : migrateTexts(project.memoryMd, project.topicals);
  // The topicals go first: a failed write then never leaves an index naming headers that were not written.
  const changed = [];
  for (const file of Object.keys(next.topicals)) {
    if (next.topicals[file] === project.topicals[file]) continue;
    fs.writeFileSync(path.join(root, file), next.topicals[file]);
    changed.push(file);
  }
  if (next.memoryMd !== project.memoryMd) {
    fs.writeFileSync(project.memoryFile, next.memoryMd);
    changed.push('memory.md');
  }
  write(changed.length ? `memory ${command}: changed ${changed.join(', ')}\n` : `memory ${command}: nothing to change\n`);
  return 0;
}

module.exports = { parseHeader, renderIndex, migrateTexts, check, matchTopicals, cli };
